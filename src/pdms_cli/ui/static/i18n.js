function t(text, vars = {}) {
  const translated = (CATALOG[language] || {})[text] ?? text;
  return translated.replace(/\{(\w+)\}/g, (whole, name) => (name in vars ? String(vars[name]) : whole));
}

function N_(text) {
  return text;
}

function squash(text) {
  return text.replace(/\s+/g, " ").trim();
}

function phrase(node) {
  const elements = [...node.children];
  return elements.length > 0 && elements.every((child) => PHRASE_TAGS.has(child.tagName) && !child.attributes.length && !child.children.length)
    && [...node.childNodes].some((child) => child.nodeType === Node.TEXT_NODE && child.textContent.trim());
}

// Remember the English of every static text once, before the scripts change any of them.
function collectStatics(node) {
  if (["SCRIPT", "STYLE", "TEXTAREA"].includes(node.tagName) || node.getAttribute("translate") === "no") return;
  for (const attr of TRANSLATED_ATTRS) {
    if (node.hasAttribute(attr) && node.getAttribute(attr).trim()) statics.push([node, node.getAttribute(attr), attr]);
  }
  if (phrase(node)) {
    statics.push([node, squash(node.innerHTML), "html"]);
    return;
  }
  for (const child of node.childNodes) {
    if (child.nodeType === Node.TEXT_NODE && child.textContent.trim()) statics.push([child, child.textContent, "text"]);
    else if (child.nodeType === Node.ELEMENT_NODE) collectStatics(child);
  }
}

function translateStatics() {
  for (const [node, english, how] of statics) {
    if (how === "html") node.innerHTML = t(english);
    else if (how === "text") {
      const [, before, text, after] = english.match(/^(\s*)([\s\S]*?)(\s*)$/);
      node.textContent = before + t(squash(text)) + after;
    } else node.setAttribute(how, t(english));
  }
}

// True when the language changed (the caller repaints what the scripts wrote).
function useLanguage(lang) {
  const next = LANGUAGES.includes(lang) ? lang : "en";
  if (next === language) return false;
  language = next;
  document.documentElement.lang = next;
  translateStatics();
  return true;
}

